import { CoworkVMManager, VMInfo } from "./vm-manager"
import { VM_AGENT_TOOLS, AgentTool } from "./agent-tools"

type Role = "system" | "user" | "assistant" | "tool"
export interface AgentMessage {
  role: Role
  content: string
  name?: string
  tool_call_id?: string
  tool_calls?: any[]
}

export interface AgentStepEvent {
  step: number
  type: "thinking" | "tool_call" | "tool_result" | "final_response" | "error"
  tool?: string
  input?: any
  output?: string
  content?: string
}

export class VMAgentFramework {
  private apiKey: string
  private model: string
  private vmName: string

  constructor(options: { apiKey?: string; model?: string; vmName: string }) {
    this.apiKey = options.apiKey || process.env.ZRO_API_KEY?.trim() || ""
    this.model = options.model || "deepseek-v4.1-flash"
    this.vmName = options.vmName
  }

  private apiEndpoint(): string {
    return process.env.ZRO_API_KEY?.trim()
      ? "https://zro.moonmath.ai/v1/chat/completions"
      : "https://openrouter.ai/api/v1/chat/completions"
  }

  /**
   * Run the agentic loop with tools inside the 500MB / 1 CPU Incus container
   */
  async *runLoop(
    userInstruction: string,
    history: { role: "user" | "assistant"; content: string }[] = [],
    maxSteps: number = 8
  ): AsyncGenerator<AgentStepEvent, string, void> {
    // 1. Ensure user's VM is ready and allocated
    const vm: VMInfo = await CoworkVMManager.getOrCreateVM(this.vmName)

    const systemPrompt = `You are Evolingo Cowork Agent, an autonomous agentic AI operating inside a dedicated, isolated Incus LXC container allocated specifically for this user.
Container Specs:
- Hardware limits: ${vm.memoryLimit} RAM, ${vm.cpuLimit} CPU
- OS: Alpine Linux Edge with bash, python3, pip, node.js, npm, git, curl
- Architecture: x86_64 LXC container managed via Incus

You have direct access to tools to execute bash commands, write files, inspect logs, and test code.
Always verify code or commands by running them with the 'bash' tool.
When using tools, emit standard function calls or format your tool action.
Keep user answers clear, insightful, and practical.`

    const toolsForAPI = Object.values(VM_AGENT_TOOLS).map((t) => ({
      type: "function",
      function: {
        name: t.name,
        description: t.description,
        parameters: t.parameters,
      },
    }))

    const messages: any[] = [
      { role: "system", content: systemPrompt },
      ...history.map((h) => ({ role: h.role, content: h.content })),
      { role: "user", content: userInstruction },
    ]

    let step = 0
    while (step < maxSteps) {
      step++
      yield { step, type: "thinking" }

      const response = await fetch(this.apiEndpoint(), {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${this.apiKey}`,
        },
        body: JSON.stringify({
          model: this.model,
          messages,
          tools: toolsForAPI,
          tool_choice: "auto",
          temperature: 0.2,
          max_tokens: 1500,
        }),
      })

      if (!response.ok) {
        const errText = await response.text()
        yield { step, type: "error", output: `API error (${response.status}): ${errText}` }
        return `Failed to execute agent step: ${errText}`
      }

      const data: any = await response.json()
      const choice = data.choices?.[0]
      const message = choice?.message

      if (!message) {
        yield { step, type: "error", output: "No response from model" }
        return "No response generated by model."
      }

      messages.push(message)

      // Check if tool calls were requested
      if (message.tool_calls && message.tool_calls.length > 0) {
        for (const tc of message.tool_calls) {
          const fnName = tc.function?.name
          let fnArgs: any = {}
          try {
            fnArgs = JSON.parse(tc.function?.arguments || "{}")
          } catch {
            fnArgs = { command: tc.function?.arguments }
          }

          yield {
            step,
            type: "tool_call",
            tool: fnName,
            input: fnArgs,
          }

          const tool = VM_AGENT_TOOLS[fnName]
          let result = ""
          if (tool) {
            try {
              result = await tool.execute(fnArgs, this.vmName)
            } catch (err: any) {
              result = `Tool execution error: ${err.message}`
            }
          } else {
            result = `Unknown tool: ${fnName}`
          }

          yield {
            step,
            type: "tool_result",
            tool: fnName,
            output: result,
          }

          messages.push({
            role: "tool",
            tool_call_id: tc.id,
            content: result,
          })
        }
        // Continue loop to give model the tool results
        continue
      }

      // No tool calls -> Final response
      const finalText = message.content || ""
      yield {
        step,
        type: "final_response",
        content: finalText,
      }
      return finalText
    }

    return "Agent reached maximum execution steps."
  }
}
